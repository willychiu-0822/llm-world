import { expect } from "@playwright/test";
import { test } from "./helpers";
import { evidence, seedPredecessor } from "./helpers";


test("UAT-01 P2-7 新手從訪客走到第一個事蹟與鏡子", async ({ page }) => {
  test.fixme(true, "P2-2/P2-3：匿名 session 與管理權限檢查修好後啟用，console error 必須為 0");
  await seedPredecessor();
  const errors: string[] = [];
  page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
  page.on("pageerror", e => errors.push(e.message));
  const snap = async (step: string) => evidence(page, `UAT-01-${step}`);
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "歡迎來到龍角鎮" })).toBeVisible();
  await snap("01-home");
  await page.getByRole("link", { name: "先隨便看看" }).click();
  await expect(page.locator("#map")).toBeInViewport();
  await snap("02-browse-map");
  await page.getByRole("link", { name: "進入小鎮" }).click();
  await snap("03-login");
  await page.getByLabel("Email").fill("novice@e2e.test");
  await page.getByLabel("名字", { exact: true }).fill("新手小安");
  await page.getByRole("button", { name: "開發用登入" }).click();
  await page.getByRole("link", { name: "設定角色", exact: true }).click();
  await snap("04-character");
  await page.getByLabel("角色名字").fill("第一次來的小龍");
  await page.getByRole("button", { name: "儲存角色" }).click();
  await expect(page.getByText("角色已儲存", { exact: false })).toBeVisible();
  await snap("05-saved");
  await page.getByLabel("想做的事", { exact: true }).fill("想試試唱歌");
  await page.getByLabel("主題區").selectOption("music");
  await page.getByRole("button", { name: "寫下來" }).click();
  await expect(page.getByText("想試試唱歌", { exact: true })).toBeVisible();
  await snap("06-want");
  await page.getByRole("link", { name: "龍角鎮首頁" }).click();
  await page.getByRole("link", { name: /音樂坊/ }).click();
  await expect(page.getByRole("heading", { name: "音樂坊", exact: true })).toBeVisible();
  await snap("07-place");
  await page.getByRole("link", { name: /去上一次聲樂試用課/ }).click();
  await snap("08-deed");
  await page.getByRole("link", { name: "我也想做", exact: true }).click();
  await expect(page.getByRole("heading", { name: "定義你的第一步" })).toBeVisible();
  await snap("09-me-too");
  await page.getByLabel("第一步", { exact: true }).fill("今天先在家唱一首歌");
  await page.getByRole("button", { name: "確定這一步" }).click();
  await expect(page.getByRole("heading", { name: "「今天先在家唱一首歌」" })).toBeVisible();
  await snap("10-first-step");
  await page.getByRole("button", { name: "我做到了", exact: true }).click();
  await page.getByLabel("做之後的隨筆（選填）").fill("原來真的可以從很小的一步開始");
  await snap("11-completing");
  await page.getByRole("button", { name: "完成", exact: true }).click();
  // P1-2 pins completion feedback separately; this journey follows the completed tab too.
  await page.getByRole("tab", { name: /完成了/ }).click();
  await expect(page.getByRole("link", { name: "看看這個事蹟" })).toBeVisible();
  await snap("12-done");
  await page.getByRole("link", { name: "看看這個事蹟" }).click();
  await expect(page).toHaveURL(/\/deeds\//);
  await snap("13-my-deed");
  const nav = page.getByRole("navigation", { name: test.info().project.name === "mobile" ? "快速導覽" : "主要導覽" });
  await nav.getByRole("link", { name: "鏡子", exact: true }).click();
  await expect(page.getByText("已經有 1 步成真")).toBeVisible();
  await snap("14-mirror");
  await nav.getByRole("link", { name: test.info().project.name === "mobile" ? "發現" : "發現匣", exact: true }).click();
  await snap("15-discoveries");
  await page.goto("/connect");
  await expect(page.locator("code", { hasText: "/mcp" })).toBeVisible();
  await snap("16-connect");
  expect(errors).toEqual([]);
});
